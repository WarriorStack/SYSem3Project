import { useState } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { FileText } from "lucide-react";
import { PageHeader, Panel } from "@/components/common/PageHeader";
import { SearchFilter } from "@/components/common/SearchFilter";
import { SeverityBadge, StatusBadge } from "@/components/common/SeverityBadge";
import { EmptyState, ErrorState, LoadingState } from "@/components/common/States";
import { reportService } from "@/lib/api/services";
import { toErrorState } from "@/lib/api/query";
import { formatDate, formatDateTime, formatNumber, titleCase } from "@/lib/format";

export const Route = createFileRoute("/_app/reports")({
  head: () => ({
    meta: [
      { title: "Security Reports — SentinelML" },
      {
        name: "description",
        content: "Backend-generated detection, attack, severity and risk summaries by date range.",
      },
      { property: "og:title", content: "Security Reports — SentinelML" },
      {
        property: "og:description",
        content: "Backend-generated detection, attack, severity and risk summaries by date range.",
      },
    ],
  }),
  component: ReportsPage,
});

function StatGrid({ title, values }: { title: string; values: Record<string, number> }) {
  const entries = Object.entries(values ?? {});
  if (entries.length === 0) return null;
  return (
    <div>
      <p className="text-muted-foreground mb-2 text-[11px] tracking-wider uppercase">{title}</p>
      <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        {entries.map(([key, value]) => (
          <div key={key} className="bg-secondary/40 rounded-md border p-3">
            <dt className="text-muted-foreground text-xs">{titleCase(key)}</dt>
            <dd className="mt-0.5 font-mono text-lg font-semibold">{formatNumber(value)}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

function ReportsPage() {
  const [dateFrom, setDateFrom] = useState("");
  const [dateTo, setDateTo] = useState("");

  const query = useQuery({
    queryKey: ["reports", { dateFrom, dateTo }],
    queryFn: () => reportService.list({ start_date: dateFrom, end_date: dateTo }),
  });

  const reports = query.data?.items ?? [];
  const error = toErrorState(query.error);

  return (
    <>
      <PageHeader
        title="Reports"
        description="Summarised security posture for a reporting period, generated by the backend."
      />

      <Panel>
        <SearchFilter
          dateFrom={dateFrom}
          dateTo={dateTo}
          onDateFromChange={setDateFrom}
          onDateToChange={setDateTo}
          onReset={() => {
            setDateFrom("");
            setDateTo("");
          }}
        />

        {query.isLoading ? (
          <LoadingState label="Generating report view…" />
        ) : error ? (
          <ErrorState message={error.message} onRetry={() => void query.refetch()} />
        ) : reports.length === 0 ? (
          <EmptyState
            icon={<FileText className="size-5" />}
            title="No reports available"
            message="Reports appear once the backend has data for the selected period."
          />
        ) : (
          <div className="space-y-6 p-4">
            {reports.map((report, index) => (
              <article key={String(report.id ?? index)} className="space-y-5 rounded-lg border p-4">
                <header className="flex flex-wrap items-center justify-between gap-3 border-b pb-3">
                  <div>
                    <h2 className="text-sm font-semibold">
                      {report.title ?? "Security summary report"}
                    </h2>
                    <p className="text-muted-foreground text-xs">
                      {formatDate(report.start_date)} – {formatDate(report.end_date)}
                    </p>
                  </div>
                  <p className="text-muted-foreground font-mono text-xs">
                    Generated {formatDateTime(report.generated_at)}
                  </p>
                </header>

                <StatGrid title="Detection statistics" values={report.detection_stats ?? {}} />
                <StatGrid title="Severity statistics" values={report.severity_stats ?? {}} />

                {(report.attack_stats ?? []).length > 0 && (
                  <div>
                    <p className="text-muted-foreground mb-2 text-[11px] tracking-wider uppercase">
                      Attack statistics
                    </p>
                    <ul className="divide-y rounded-md border">
                      {(report.attack_stats ?? []).map((stat) => (
                        <li key={stat.attack_type} className="flex justify-between px-3 py-2 text-sm">
                          <span>{titleCase(stat.attack_type)}</span>
                          <span className="font-mono">{formatNumber(stat.count)}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                {report.risk_summary && (
                  <div>
                    <p className="text-muted-foreground mb-2 text-[11px] tracking-wider uppercase">
                      Risk summary
                    </p>
                    <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
                      {Object.entries(report.risk_summary)
                        .filter(([, v]) => typeof v === "number" || typeof v === "string")
                        .map(([key, value]) => (
                          <div key={key} className="bg-secondary/40 rounded-md border p-3">
                            <dt className="text-muted-foreground text-xs">{titleCase(key)}</dt>
                            <dd className="mt-0.5 font-mono text-lg font-semibold">{String(value)}</dd>
                          </div>
                        ))}
                    </dl>
                  </div>
                )}

                {(report.notable_incidents ?? []).length > 0 && (
                  <div>
                    <p className="text-muted-foreground mb-2 text-[11px] tracking-wider uppercase">
                      Notable incidents
                    </p>
                    <ul className="divide-y rounded-md border">
                      {(report.notable_incidents ?? []).map((incident) => (
                        <li
                          key={String(incident.id)}
                          className="flex items-center justify-between gap-3 px-3 py-2"
                        >
                          <span className="truncate text-sm">{incident.title}</span>
                          <span className="flex items-center gap-2">
                            <SeverityBadge severity={incident.severity} />
                            <StatusBadge status={incident.status} />
                          </span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </article>
            ))}
          </div>
        )}
      </Panel>
    </>
  );
}
